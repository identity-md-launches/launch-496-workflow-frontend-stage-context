// Derives the app's runtime deployment configuration from the workflow handoff.
//
// Inputs (committed byte copies of the assignment reads):
//   deployment/handoff.json         .imd/reads/deployment.json
//   deployment/network.json         .imd/reads/network.json (optional)
//   deployment/<Contract>.abi.json  docs/abi/<Contract>.json at the deployed source commit
// Outputs:
//   public/imd-deployment.json      runtime configuration (assets filled in by finalize-manifest.mjs)
//   public/abi/<Contract>.json      raw ABI arrays, verified against the handoff abiHash
//   src/generated/pool.ts           launch pool parameters from the handoff manifest
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { canonicalKeccak, isAddress, isHex64, readJson } from './lib.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const handoff = readJson(join(root, 'deployment/handoff.json'));
const networkPath = join(root, 'deployment/network.json');
const networkFile = existsSync(networkPath) ? readJson(networkPath) : undefined;

const fail = (msg) => {
  console.error(`write-deployment: ${msg}`);
  process.exit(1);
};

if (handoff.version !== 1) fail('handoff version must be 1');
if (!Number.isInteger(handoff.chainId)) fail('handoff chainId missing');
if (!/^[0-9a-f]{40}$/.test(handoff.sourceCommit)) fail('handoff sourceCommit malformed');
if (!isHex64(handoff.attestationHash)) fail('handoff attestationHash malformed');
if (!Array.isArray(handoff.contracts) || handoff.contracts.length === 0) fail('handoff has no contracts');
if (networkFile && networkFile.network?.chainId !== handoff.chainId) {
  fail(`network.json chainId ${networkFile.network?.chainId} differs from handoff ${handoff.chainId}`);
}

mkdirSync(join(root, 'public/abi'), { recursive: true });
mkdirSync(join(root, 'src/generated'), { recursive: true });

const contracts = handoff.contracts.map((c) => {
  if (!isAddress(c.address)) fail(`${c.name}: bad address`);
  if (!isHex64(c.abiHash)) fail(`${c.name}: bad abiHash`);
  const abi = readJson(join(root, `deployment/${c.name}.abi.json`));
  if (!Array.isArray(abi)) fail(`${c.name}: ABI export is not a JSON array`);
  const hash = canonicalKeccak(abi);
  if (hash !== c.abiHash) fail(`${c.name}: ABI hash ${hash} does not match handoff ${c.abiHash}`);
  const abiPath = `abi/${c.name}.json`;
  writeFileSync(join(root, 'public', abiPath), `${JSON.stringify(abi, null, 2)}\n`);
  return { name: c.name, address: c.address, abiHash: c.abiHash, abiPath };
});

const manifest = {
  version: 1,
  launchId: handoff.launchId,
  chainId: handoff.chainId,
  sourceCommit: handoff.sourceCommit,
  attestationHash: handoff.attestationHash,
  contracts,
  assets: [],
};
if (networkFile?.network) manifest.network = networkFile.network;
if (networkFile?.walletAddChain) manifest.walletAddChain = networkFile.walletAddChain;

writeFileSync(join(root, 'public/imd-deployment.json'), `${JSON.stringify(manifest, null, 2)}\n`);

const pool = handoff.manifest?.pool;
const token = handoff.manifest?.token;
if (!pool || !isAddress(pool.pairedCurrency)) fail('handoff manifest.pool missing');
const deploymentBlock = Math.min(...handoff.contracts.map((c) => Number(c.blockNumber ?? 0)).filter((n) => Number.isFinite(n)));
const poolTs = `// Generated by scripts/write-deployment.mjs from deployment/handoff.json. Do not edit.
// Launch pool parameters of the attested manifest (launch ${handoff.launchId}).
/** Earliest deployment block of the handoff contracts; log queries start here. */
export const DEPLOYMENT_BLOCK = ${Number.isFinite(deploymentBlock) ? deploymentBlock : 0};
export const LAUNCH_POOL = {
  pairedCurrency: '${pool.pairedCurrency.toLowerCase()}',
  fee: ${Number(pool.fee)},
  tickSpacing: ${Number(pool.tickSpacing)},
  initialSqrtPriceX96: '${String(pool.initialPrice)}',
  tokenContract: '${token?.contract ?? 'LaunchToken'}',
  tokenSymbol: '${token?.symbol ?? ''}',
  tokenDecimals: ${Number(token?.decimals ?? 18)},
} as const;
`;
writeFileSync(join(root, 'src/generated/pool.ts'), poolTs);

console.log(
  `write-deployment: ${contracts.length} contract ABI(s) verified for chain ${handoff.chainId}, launch ${handoff.launchId}`,
);
